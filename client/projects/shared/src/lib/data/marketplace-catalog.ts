export interface MarketplaceCatalogItem {
  key: string;
  name: string;
  teluguName: string;
  pack: string;
  image: string;
  packOptions: string[];
  /** 'weight' (g/kg) or 'volume' (ml/L) when this item can take a custom typed quantity; null for piece/bunch items. */
  unitFamily: 'weight' | 'volume' | null;
}

export interface MarketplaceCategory {
  key: string;
  label: string;
  icon: string;
  bg: string;
  items: MarketplaceCatalogItem[];
}

function parsePack(pack: string): { value: number; unit: 'g' | 'ml' } | null {
  const match = pack.match(/^(\d+(?:\.\d+)?)\s*(kg|g|l|ml)$/i);
  if (!match) return null;
  const value = parseFloat(match[1]);
  const unit = match[2].toLowerCase();
  if (unit === 'kg') return { value: value * 1000, unit: 'g' };
  if (unit === 'l') return { value: value * 1000, unit: 'ml' };
  return { value, unit: unit as 'g' | 'ml' };
}

function trimZeros(n: number): string {
  return Number.isInteger(n) ? String(n) : String(Math.round(n * 100) / 100);
}

export function formatCustomPack(value: number, unit: 'g' | 'kg' | 'ml' | 'L'): string {
  return `${trimZeros(Math.round(value * 100) / 100)} ${unit}`;
}

function formatPack(value: number, unit: 'g' | 'ml'): string {
  if (value >= 1000) {
    return `${trimZeros(value / 1000)} ${unit === 'g' ? 'kg' : 'L'}`;
  }
  return `${trimZeros(value)} ${unit}`;
}

/** half / same / double / quadruple the base pack — covers "half kg / 1 kg / 2 kg" style picking. */
function packOptionsFor(pack: string): string[] {
  const parsed = parsePack(pack);
  if (!parsed) return [pack];

  const seen = new Set<string>();
  const options: string[] = [];
  for (const multiplier of [0.5, 1, 2, 4]) {
    const formatted = formatPack(parsed.value * multiplier, parsed.unit);
    if (!seen.has(formatted)) {
      seen.add(formatted);
      options.push(formatted);
    }
  }
  return options;
}

function category(
  key: string,
  label: string,
  icon: string,
  bg: string,
  items: [string, string, string, string, string][],
): MarketplaceCategory {
  return {
    key,
    label,
    icon,
    bg,
    items: items.map(([itemKey, name, teluguName, pack, image]) => {
      const parsed = parsePack(pack);
      return {
        key: itemKey,
        name,
        teluguName,
        pack,
        image,
        packOptions: packOptionsFor(pack),
        unitFamily: parsed ? (parsed.unit === 'g' ? ('weight' as const) : ('volume' as const)) : null,
      };
    }),
  };
}

